#!/usr/bin/env python3
"""Generates llms-full.txt — the whole document set in one fetch.

Run from anywhere: python3 admin/build/gen_llms_full.py

Why this file exists: an agent that tried to consume the parent site's documentation
reported that the index fetch worked and then LINK-FOLLOWING FAILED, because agent
fetch tools frequently refuse URLs a search has not already returned. The conclusion
was that llms.txt "is not a convenience for such agents but the whole surface"; the
second mitigation it recommends, after making each llms.txt entry carry a fact rather
than a topic, is to publish a single-file concatenation so one fetch gets everything.
briefs/06 §3 carries that requirement onto this site.

There is a second reason specific to here. This site's own thesis is that an agent
buying facts by API is the product, not a hypothetical — so being cheaply and
completely machine-readable is the site demonstrating its argument rather than merely
describing it.

This concatenates, in order: llms.txt, the front page's markdown twin, and every
markdown document in the brief pack. It does NOT include the prose of the rendered
HTML pages, and it does not inline the two machine-readable data files (the manifest
CSV and the provenance JSON) — those are structured data and are better fetched
directly. Both omissions are stated in the header rather than left to be discovered.
"""
from pathlib import Path

ROOT    = Path(__file__).resolve().parents[2]
VERSION = (ROOT / "admin/build/version.txt").read_text().strip()

ORDER = [
    "00__BRIEF.md",
    "01__thesis-and-themes.md",
    "02__source-provenance-and-attribution.md",
    "03__corpus-index__send-repo.md",
    "04__prior-art__docs-diniscruz-ai.md",
    "05__site-architecture.md",
    "06__boundaries-and-house-style.md",
    "07__gaps-and-open-questions.md",
    "README.md",
    "PUBLIC.md",
    "LICENSE.md",
]

HEADER = f"""# newsroom.sgit.ai — everything, in one file

Site version: {VERSION}. Generated by admin/build/gen_llms_full.py — do not edit by hand.

This is /llms.txt, then the front page as markdown, then every markdown document in the
brief pack, concatenated in reading order. It exists because agent fetch tools frequently
refuse URLs a search has not already returned, which makes link-following unreliable and
makes a single-file surface the practical one. If you can make more than one request,
prefer the individual documents at https://newsroom.sgit.ai/briefs/<filename> — they are
the source of truth and this file is a concatenation of them.

The pack is published verbatim except for nine redacted identifiers, each replaced with a
visible marker and recorded in briefs/PUBLIC.md, included below.

NOT included here, deliberately:
  · the prose of the rendered HTML pages — read /llms.txt for the annotated map of those
  · briefs/08__source-manifest.csv and briefs/sources__docs-diniscruz-ai.json — structured
    data, better fetched directly at those paths than flattened into a text stream

Read this before repeating anything from this file: nothing described on this site is
running. The ten articles in /library/ are real, dated and published at docs.diniscruz.ai;
the newsroom — Trust-as-a-Service, author micropayments, the decision graph, CC-Signed —
is a design. https://newsroom.sgit.ai/shipped/index.html states the line in full.

This site's own content is CC BY 4.0. The library material it republishes is CC0 1.0
Universal at source. Third-party material quoted inside these documents stays under its
own terms.

Contents, in order:
   1. llms.txt — the annotated map, each entry carrying its page's most important fact
   2. index.md — the front page as markdown
"""


def main():
    parts = [HEADER]
    for i, name in enumerate(ORDER, start=3):
        parts.append(f"   {i:>2}. briefs/{name}\n")
    parts.append("\n")

    def section(label, path):
        rule = "=" * 78
        return f"\n\n{rule}\n== {label}\n{rule}\n\n{path.read_text()}"

    parts.append(section("llms.txt", ROOT / "llms.txt"))
    parts.append(section("index.md — the front page", ROOT / "index.md"))
    missing = []
    for name in ORDER:
        f = ROOT / "briefs" / name
        if not f.exists():
            missing.append(name)
            continue
        parts.append(section(f"briefs/{name}", f))

    out = ROOT / "llms-full.txt"
    out.write_text("".join(parts))
    words = len(out.read_text().split())
    print(f"gen_llms_full: llms-full.txt — {len(ORDER) - len(missing) + 2} sections, "
          f"{words:,} words, {out.stat().st_size:,} bytes")
    for m in missing:
        print(f"  ! briefs/{m} is missing")


if __name__ == "__main__":
    main()
